package com.planora.model;

import java.time.Instant;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * A calendar event. The end is exclusive; all-day events span whole days, from the start date at
 * midnight to the midnight after their last day.
 */
public class CalendarEvent implements Syncable {
    private String id = UUID.randomUUID().toString();
    private String title = "";
    private LocalDateTime start;
    private LocalDateTime end;
    private boolean allDay;
    private String color = "#a78bdb";
    private String location = "";
    private String notes = "";
    private Instant updatedAt;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public LocalDateTime getStart() {
        return start;
    }

    public void setStart(LocalDateTime start) {
        this.start = start;
    }

    public LocalDateTime getEnd() {
        return end;
    }

    public void setEnd(LocalDateTime end) {
        this.end = end;
    }

    public boolean isAllDay() {
        return allDay;
    }

    public void setAllDay(boolean allDay) {
        this.allDay = allDay;
    }

    public String getColor() {
        return color;
    }

    public void setColor(String color) {
        this.color = color;
    }

    public String getLocation() {
        return location;
    }

    public void setLocation(String location) {
        this.location = location;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }

    @Override
    public Instant getUpdatedAt() {
        return updatedAt;
    }

    @Override
    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
